package com.abhijeet.loganalyzer.service;

import com.abhijeet.loganalyzer.model.Finding;
import com.abhijeet.loganalyzer.model.LogSummary;
import com.fasterxml.jackson.core.JsonProcessingException;
import com.fasterxml.jackson.databind.ObjectMapper;

import java.util.LinkedHashMap;
import java.util.Map;

/**
 * Turns a summary into a document that can be downloaded and attached to a ticket. The export
 * is built from the deterministic findings only, so it costs no AI quota and is reproducible.
 */
public final class ReportExporter {

    private static final ObjectMapper MAPPER = new ObjectMapper();

    private ReportExporter() {
    }

    public static String markdown(String fileName, LogSummary s) {
        StringBuilder md = new StringBuilder();
        md.append("# Log analysis report\n\n");
        md.append("**Source:** `").append(code(fileName)).append("`  \n");
        md.append("**Risk:** ").append(s.riskLevel()).append(" (").append(s.riskScore()).append("/100)");
        if (s.firstSeen() != null && s.lastSeen() != null) {
            md.append("  \n**Period:** ").append(s.firstSeen()).append(" to ").append(s.lastSeen());
        }
        md.append("\n\n## Overview\n\n");
        md.append("| Metric | Value |\n|---|---|\n");
        md.append("| Lines | ").append(s.totalLines()).append(" |\n");
        md.append("| Parsed events | ").append(s.parsedEvents()).append(" |\n");
        md.append("| Unique addresses | ").append(s.uniqueIps()).append(" |\n");
        md.append("| Findings | ").append(s.findings().size()).append(" |\n");

        md.append("\n## Findings\n\n");
        if (s.findings().isEmpty()) {
            md.append("No findings. Traffic looks clean.\n");
        }
        int n = 1;
        for (Finding f : s.findings()) {
            md.append("### ").append(n++).append(". [").append(f.severity()).append("] ")
                    .append(text(f.title())).append("\n\n");
            md.append("- **Rule:** `").append(f.rule()).append("`\n");
            if (f.mitre() != null) {
                md.append("- **MITRE ATT&CK:** ").append(text(f.mitre())).append("\n");
            }
            md.append("- **Matching events:** ").append(f.count()).append("\n\n");
            md.append(text(f.description())).append("\n\n");
            if (!f.evidence().isEmpty()) {
                md.append("**Evidence**\n\n");
                f.evidence().forEach(line -> md.append("- ").append(text(line)).append("\n"));
                md.append("\n");
            }
            md.append("**Recommendation:** ").append(text(f.recommendation())).append("\n\n");
        }

        table(md, "Top sources", "Address", "Requests", s.topIps());
        table(md, "Status codes", "Class", "Count", s.statusClasses());
        table(md, "Top user agents", "User agent", "Requests", s.topUserAgents());
        md.append("\n---\nGenerated by AI Log Analyzer. Findings are computed deterministically from the log.\n");
        return md.toString();
    }

    public static String json(String fileName, LogSummary summary) throws JsonProcessingException {
        Map<String, Object> body = new LinkedHashMap<>();
        body.put("file", fileName);
        body.put("summary", summary);
        return MAPPER.writerWithDefaultPrettyPrinter().writeValueAsString(body);
    }

    private static void table(StringBuilder md, String title, String keyHeader, String valueHeader,
                              Map<String, Integer> rows) {
        if (rows == null || rows.isEmpty()) {
            return;
        }
        md.append("\n## ").append(title).append("\n\n");
        md.append("| ").append(keyHeader).append(" | ").append(valueHeader).append(" |\n|---|---|\n");
        rows.forEach((key, value) -> md.append("| ").append(cell(key)).append(" | ").append(value).append(" |\n"));
    }

    /** Text that came from the log may contain HTML or table syntax, so neutralise both. */
    private static String text(String value) {
        if (value == null) {
            return "";
        }
        return value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                .replaceAll("[\\r\\n]+", " ");
    }

    private static String cell(String value) {
        return text(value).replace("|", "\\|");
    }

    private static String code(String value) {
        return text(value).replace("`", "'");
    }
}
